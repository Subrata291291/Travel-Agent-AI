@dataclass
class GraphContext:
    db: Session

class TravelAgentGraph:
    """
    Main LangGraph orchestration layer.

    Responsibilities:

    - Perception
    - Destination resolution
    - Planning
    - Tool execution
    - Multi-turn transport selection
    - Explicit booking confirmation
    - Deterministic booking execution

    IMPORTANT:

    The LLM never directly performs a booking.

    Booking execution is controlled by application state.
    """

    @staticmethod
    def _as_pending_destination(value):
        if isinstance(value, dict):
            value = value.get("name")

        return value if isinstance(value, str) else None

    @staticmethod
    def _looks_like_inventory_not_a_place(value: str | None) -> bool:
        """Reject persisted search-result text as a destination clarification."""

        if not value or len(value) > 160:
            return True
        return bool(
            re.search(
                r"\b(mock|hotel|resort|option|provider|amenities|price per night)\b",
                value,
                re.IGNORECASE,
            )
        )

    @staticmethod
    def _budget_conflict_message(state: TravelState) -> str | None:
        """Return a grounded budget-conflict response when costs exceed budget."""

        perception = state.get("perception")
        if hasattr(perception, "model_dump"):
            trip = perception.model_dump()
        elif isinstance(perception, dict):
            trip = perception
        else:
            trip = {}

        booking = state.get("booking")
        if (
            not isinstance(booking, dict)
            or booking.get("status") != "confirmed"
            or not booking.get("mode")
        ):
            return None

        budget = trip.get("budget")
        start_date = trip.get("start_date")
        end_date = trip.get("end_date")
        if (
            not trip.get("destination")
            or not start_date
            or not end_date
            or not trip.get("travellers")
            or budget is None
        ):
            return None

        try:
            budget = float(budget)
            nights = (date.fromisoformat(end_date) - date.fromisoformat(start_date)).days
            transport_total = float(booking["total_price"])
        except (KeyError, TypeError, ValueError):
            return None

        if nights <= 0:
            return None

        currency = trip.get("currency") or "INR"
        if booking.get("currency") != currency:
            return None

        hotel_totals = []
        for hotel in state.get("hotel_options", []):
            if not isinstance(hotel, dict):
                continue
            if (
                hotel.get("check_in_date") != start_date
                or hotel.get("check_out_date") != end_date
                or hotel.get("currency", "INR") != currency
            ):
                continue
            try:
                hotel_total = float(hotel["total_price"])
            except (KeyError, TypeError, ValueError):
                try:
                    hotel_total = float(hotel["price_per_night"]) * nights
                except (KeyError, TypeError, ValueError):
                    continue
            hotel_totals.append((hotel_total, hotel))

        if not hotel_totals:
            return None

        hotel_total, hotel = min(hotel_totals, key=lambda item: item[0])
        total = transport_total + hotel_total
        over_budget = total - budget
        if over_budget <= 0:
            return None

        transport_name = booking.get("option_id") or booking.get("mode", "transport")
        hotel_name = hotel.get("name") or hotel.get("hotel_id", "available hotel")
        hotel_id = hotel.get("hotel_id")
        hotel_label = f"{hotel_name} ({hotel_id})" if hotel_id else hotel_name
        return (
            f"Your confirmed {transport_name} booking costs {currency} "
            f"{transport_total:,.0f}, and the lowest-priced available hotel, "
            f"{hotel_label}, costs {currency} {hotel_total:,.0f}. The total is "
            f"{currency} {total:,.0f}, which is {currency} {over_budget:,.0f} "
            f"over your {currency} {budget:,.0f} total trip budget. Would you "
            "like to increase your budget or choose a different transport option?"
        )

    @staticmethod
    def _selected_destination_candidate(state: TravelState):
        if state.get("pending_clarification") != "destination":
            return None

        candidates = state.get("pending_destination_candidates") or []
        selection = str(state.get("user_message", "")).strip()
        if not selection.isdigit():
            return None

        index = int(selection) - 1
        if not 0 <= index < len(candidates):
            return None

        candidate = candidates[index]
        return candidate if isinstance(candidate, dict) else None

