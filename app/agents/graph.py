    def booking_confirmation_node(
        self,
        state: TravelState,
    ):
        """
        Validate the selected transport option and ask
        for explicit confirmation.

        This node NEVER creates a booking.
        """

        perception = state.get(
            "perception"
        )

        if not perception:

            return {
                "messages": [
                    AIMessage(
                        content=(
                            "I couldn't determine which "
                            "transport option you want to book."
                        )
                    )
                ],
                "pending_booking_confirmation": False,
            }

        selected_option_id = (
            perception.selected_option_id
        )

        if not selected_option_id:

            return {
                "messages": [
                    AIMessage(
                        content=(
                            "Please provide the transport "
                            "option ID you want to book, "
                            "such as TRAIN-1."
                        )
                    )
                ],
                "pending_booking_confirmation": False,
            }

        # ----------------------------------------------------
        # Previous search results
        # ----------------------------------------------------

        transport_options = state.get(
            "transport_options",
            [],
        )

        selected_option = next(
            (
                option
                for option in transport_options
                if option.get("option_id")
                == selected_option_id
            ),
            None,
        )

        # ----------------------------------------------------
        # Option not found
        # ----------------------------------------------------

        if not selected_option:

            return {
                "messages": [
                    AIMessage(
                        content=(
                            f"I couldn't find transport option "
                            f"{selected_option_id} from the previous "
                            "search results. Please search for transport "
                            "options again."
                        )
                    )
                ],
                "selected_option_id": (
                    selected_option_id
                ),
                "pending_booking_confirmation": False,
            }

        # ----------------------------------------------------
        # Build confirmation message
        # ----------------------------------------------------

        confirmation_message = (
            f"I found {selected_option_id}.\n\n"
            f"Mode: {selected_option.get('mode')}\n"
            f"Provider: {selected_option.get('provider')}\n"
            f"From: {selected_option.get('origin')}\n"
            f"To: {selected_option.get('destination')}\n"
            f"Departure: {selected_option.get('departure_time')}\n"
            f"Arrival: {selected_option.get('arrival_time')}\n"
            f"Duration: {selected_option.get('duration_minutes')} minutes\n"
            f"Price per traveller: {selected_option.get('price')} "
            f"{selected_option.get('currency')}\n"
            + (
                f"Total for {selected_option.get('travellers')} travellers: "
                f"{selected_option.get('total_price')} "
                f"{selected_option.get('currency')}\n"
                if selected_option.get("total_price") is not None
                else ""
            )
            + "\n"
            "Do you want me to book this option?"
        )

        return {
            "messages": [
                AIMessage(
                    content=confirmation_message
                )
            ],

            "selected_option_id": (
                selected_option_id
            ),

            "pending_booking_confirmation": True,
            "pending_booking_domain": "transport",
        }


    def hotel_booking_confirmation_node(
        self,
        state: TravelState,
    ):
        """
        Validate the requested hotel option and ask for
        explicit user confirmation.

        IMPORTANT:
        - Does NOT create a booking.
        - Uses trusted hotel_options from application state.
        - The actual database transaction happens only
        after explicit confirmation.
        """

        perception = state.get("perception")

        if not perception:
            return {
                "messages": [
                    AIMessage(
                        content=(
                            "I couldn't determine which hotel "
                            "you want to book."
                        )
                    )
                ],
                "pending_booking_confirmation": False,
            }

        selected_hotel_id = perception.selected_option_id

        if not selected_hotel_id:
            return {
                "messages": [
                    AIMessage(
                        content=(
                            "Please provide the hotel option ID "
                            "you want to book, such as HOTEL-2."
                        )
                    )
                ],
                "pending_booking_confirmation": False,
            }

        # --------------------------------------------------------
        # Read trusted hotel results from application state.
        # --------------------------------------------------------

        hotel_options = state.get(
            "hotel_options",
            [],
        )

        selected_hotel = next(
            (
                hotel
                for hotel in hotel_options
                if selected_hotel_id.casefold() in {
                    str(hotel.get("hotel_id", "")).casefold(),
                    str(hotel.get("supplier_offer_id", "")).casefold(),
                }
            ),
            None,
        )

        # --------------------------------------------------------
        # Hotel was not found.
        # --------------------------------------------------------

        if not selected_hotel:
            return {
                "messages": [
                    AIMessage(
                        content=(
                            f"I couldn't find hotel option "
                            f"{selected_hotel_id} from the previous "
                            "hotel search results. Please search "
                            "for hotels again."
                        )
                    )
                ],
                "selected_option_id": None,
                "pending_booking_confirmation": False,
            }

        # --------------------------------------------------------
        # Extract trusted hotel information.
        # --------------------------------------------------------

        hotel_name = selected_hotel.get(
            "name",
            selected_hotel_id,
        )

        destination = selected_hotel.get(
            "destination",
            "",
        )

        check_in_date = selected_hotel.get(
            "check_in_date",
            "",
        )

        check_out_date = selected_hotel.get(
            "check_out_date",
            "",
        )

        price_per_night = selected_hotel.get(
            "price_per_night"
        )

        currency = selected_hotel.get(
            "currency",
            "INR",
        )

        rating = selected_hotel.get(
            "rating"
        )

        amenities = selected_hotel.get(
            "amenities",
            [],
        )

        # --------------------------------------------------------
        # Build explicit confirmation message.
        # --------------------------------------------------------

        details = [
            f"Hotel: {hotel_name}",
            f"Hotel ID: {selected_hotel_id}",
            f"Destination: {destination}",
            f"Check-in: {check_in_date}",
            f"Check-out: {check_out_date}",
            f"Price per night: {price_per_night} {currency}",
        ]

        if rating is not None:
            details.append(
                f"Rating: {rating}/5"
            )

        if amenities:
            details.append(
                "Amenities: " + ", ".join(amenities)
            )

        confirmation_message = (
            "I found the following hotel:\n\n"
            + "\n".join(details)
            + "\n\n"
            "Do you want me to create an internal booking record? This does not reserve a room with the supplier."
        )

        return {
            "messages": [
                AIMessage(
                    content=confirmation_message
                )
            ],
            "selected_option_id": selected_hotel_id,
            "pending_booking_confirmation": True,
            "pending_booking_domain": "hotel",
        }


    def hotel_existing_booking_node(
        self,
        state: TravelState,
        runtime: Runtime[GraphContext],
    ):
        """Report the persisted status of this session's hotel booking."""

        booking_state = state.get("booking") or {}
        booking_id = booking_state.get("booking_id")
        selected_hotel_id = (
            state.get("perception").selected_option_id
            if state.get("perception")
            else None
        ) or booking_state.get("hotel_id")

        try:
            booking = HotelBookingService(runtime.context.db).get_booking(
                booking_id=booking_id,
                user_id=state["user_id"],
                tenant_id=state["tenant_id"],
            )
        except (ValueError, TypeError):
            return {
                "messages": [
                    AIMessage(content="I couldn't verify the existing hotel booking. Please check its booking details.")
                ],
                "selected_option_id": None,
                "pending_booking_confirmation": False,
                "pending_booking_domain": None,
            }

        if (
            booking.session_id != state.get("session_id")
            or booking.hotel_id != selected_hotel_id
        ):
            return {
                "messages": [
                    AIMessage(content="I couldn't verify a matching hotel booking for this session.")
                ],
                "selected_option_id": None,
                "pending_booking_confirmation": False,
                "pending_booking_domain": None,
            }

        if booking.status == "confirmed":
            message = (
                "This hotel booking is already confirmed.\n\n"
                f"Booking ID: {booking.booking_id}\n"
                f"Hotel: {booking.hotel_name}\n"
                f"Check-in: {booking.check_in_date}\n"
                f"Check-out: {booking.check_out_date}\n"
                f"Total price: {booking.total_price} {booking.currency}\n"
                f"Status: {booking.status}"
            )
        else:
            message = (
                f"This hotel booking is {booking.status}. It is not currently confirmed.\n\n"
                f"Booking ID: {booking.booking_id}\n"
                f"Status: {booking.status}"
            )

        return {
            "messages": [AIMessage(content=message)],
            "booking": booking.model_dump(),
            "selected_option_id": None,
            "pending_booking_confirmation": False,
            "pending_booking_domain": None,
        }

