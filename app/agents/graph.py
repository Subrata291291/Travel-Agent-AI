    def get_booking_details_node(
        self,
        state: TravelState,
    ) -> TravelState:
        
        """
        Fetch and return details of one existing booking.

        Booking IDs are globally unique across the current
        transport and hotel booking tables, so we first try
        hotel booking lookup and then transport booking lookup.

        The booking domain is resolved from the database rather
        than relying on the LLM.
        """

        perception = state["perception"]

        booking_id = perception.booking_id

        state["answer"] = (
            f"I couldn't find any booking with ID "
            f"{booking_id}."
        )

        return state

        # ======================================================
        # 1. Try HOTEL booking
        # ======================================================

        try:
            hotel_booking = (
                self.hotel_booking_service.get_booking(
                    booking_id,
                    state["user_id"],
                )
            )

            state["answer"] = (
                "Here are your hotel booking details:\n\n"
                f"Booking ID: {hotel_booking.booking_id}\n"
                f"Hotel: {hotel_booking.hotel_name}\n"
                f"Destination: {hotel_booking.destination}\n"
                f"Provider: {hotel_booking.provider}\n"
                f"Check-in: {hotel_booking.check_in_date}\n"
                f"Check-out: {hotel_booking.check_out_date}\n"
                f"Travellers: {hotel_booking.travellers}\n"
                f"Nights: {hotel_booking.nights}\n"
                f"Price per night: "
                f"{hotel_booking.currency} "
                f"{hotel_booking.price_per_night:.2f}\n"
                f"Total price: "
                f"{hotel_booking.currency} "
                f"{hotel_booking.total_price:.2f}\n"
                f"Status: {hotel_booking.status}\n"
                f"Created at: {hotel_booking.created_at}"
            )

            print(
                ">>> BOOKING DETAILS ANSWER:",
                state["answer"]
            )

            return state

        except ValueError:
            # Not a hotel booking.
            pass

        # ======================================================
        # 2. Try TRANSPORT booking
        # ======================================================

        try:
            booking = self.booking_service.get_booking(
                booking_id,
                state["user_id"],
            )

            state["answer"] = (
                "Here are your transport booking details:\n\n"
                f"Booking ID: {booking.booking_id}\n"
                f"Mode: {booking.mode}\n"
                f"Provider: {booking.provider}\n"
                f"From: {booking.origin}\n"
                f"To: {booking.destination}\n"
                f"Departure: {booking.departure_time}\n"
                f"Arrival: {booking.arrival_time}\n"
                f"Duration: {booking.duration_minutes} minutes\n"
                f"Travellers: {booking.travellers}\n"
                f"Price per traveller: "
                f"{booking.currency} "
                f"{booking.price:.2f}\n"
                f"Total price: "
                f"{booking.currency} "
                f"{booking.total_price:.2f}\n"
                f"Status: {booking.status}\n"
                f"Created at: {booking.created_at}"
            )

            return state

        except PermissionError:
            state["answer"] = (
                f"I couldn't find a booking with ID {booking_id}."
            )
            return state

        except ValueError:
            pass

        # ======================================================
        # 3. Booking not found
        # ======================================================

        state["response"] = (
            f"I couldn't find any booking with ID "
            f"{booking_id}."
        )

        return state

