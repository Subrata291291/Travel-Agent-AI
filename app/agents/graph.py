class TravelState(TypedDict):
    """
    Shared state passed through every LangGraph node.

    This state contains both current-turn information and
    important multi-turn workflow information.

    Important booking fields:

    - transport_options
    - selected_option_id
    - pending_booking_confirmation
    - booking
    """

    user_message: str
    user_id: str
    session_id: str
    tenant_id: str

    messages: Annotated[
        list[BaseMessage],
        add_messages,
    ]

    perception: object | None
    plan: object | None

    destination_resolution: dict | None

    clarification_needed: bool
    pending_clarification: str | None
    pending_destination: str | None
    pending_destination_candidates: list[dict]

    tool_context: ToolContext | None

    trip_context: dict | None

    # Transport options discovered in previous turns.
    transport_options: list[dict]

    # Selected option, for example TRAIN-1.
    selected_option_id: str | None

    # True when application is waiting for explicit
    # booking confirmation.
    pending_booking_confirmation: bool
    # True when application is waiting for explicit
    # hotel booking confirmation.
    pending_booking_domain: str | None


    # Booking ID waiting for explicit cancellation confirmation.
    pending_cancellation_booking_id: str | None

    # Final booking information after successful booking.
    booking: dict | None

    # Hotel options discovered in previous turns.
    hotel_options: list[dict]

    # Transient marker used to gate recommendations after hotel search.
    hotel_search_performed: bool

    # Transient marker used to render transport search results from state.
    transport_search_performed: bool
    transport_search_error: str | None
    hotel_search_error: str | None

    # Final response generated by deterministic application logic.
    answer: str | None


