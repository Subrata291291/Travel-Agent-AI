    def execute_existing_cancellation_node(
        self,
        state: TravelState,
        runtime: Runtime[GraphContext],
    ):
        """
        Cancel an already-created booking.

        IMPORTANT:

        This node performs a real database state change.

        The LLM does not cancel the booking.

        The perception layer only identifies:
            intent = cancel_booking
            booking_id = BOOK-...

        This node calls BookingService, which performs:
            - booking lookup
            - ownership validation
            - status validation
            - database update
            - commit
        """

        # ----------------------------------------------------
        # Get current user
        # ----------------------------------------------------

        user_id = state.get("user_id")

        if not user_id:

            return {
                "messages": [
                    AIMessage(
                        content=(
                            "I couldn't determine your user "
                            "account for this cancellation."
                        )
                    )
                ]
            }

        # ----------------------------------------------------
        # Get perception
        # ----------------------------------------------------

        perception = state.get("perception")

        if not perception:

            return {
                "messages": [
                    AIMessage(
                        content=(
                            "I couldn't understand which booking "
                            "you want to cancel."
                        )
                    )
                ]
            }

        # ----------------------------------------------------
        # Get booking ID
        # ----------------------------------------------------

        booking_id = (
            state.get("pending_cancellation_booking_id")
            or getattr(
                perception,
                "booking_id",
                None,
            )
        )

        # ----------------------------------------------------
        # Booking ID missing
        # ----------------------------------------------------

        if not booking_id:

            return {
                "messages": [
                    AIMessage(
                        content=(
                            "Please provide the booking ID "
                            "you want to cancel."
                        )
                    )
                ]
            }

        # ----------------------------------------------------
        # Execute cancellation
        # ----------------------------------------------------

        try:

            # ------------------------------------------------
            # First determine whether this is a hotel booking.
            #
            # Hotel and transport booking IDs intentionally use
            # the same BOOK-... format, so we must NOT decide
            # the domain from the booking ID itself.
            #
            # The application checks the hotel booking store
            # first. If the booking exists there, the hotel
            # service handles cancellation.
            # Otherwise the transport booking service handles it.
            # ------------------------------------------------

            try:

                hotel_booking = (
                    HotelBookingService(runtime.context.db).get_booking(
                        booking_id=booking_id,
                        user_id=user_id,
                        tenant_id=state["tenant_id"],
                    )
                )

            except ValueError:

                hotel_booking = None

            # ------------------------------------------------
            # Hotel booking
            # ------------------------------------------------

            if hotel_booking:

                cancelled_booking = (
                    HotelBookingService(runtime.context.db).cancel_booking(
                        booking_id=booking_id,
                        user_id=user_id,
                        tenant_id=state["tenant_id"],
                    )
                )

                message = (
                    "Your hotel booking has been "
                    "cancelled successfully.\n\n"
                    f"Booking ID: "
                    f"{cancelled_booking.booking_id}\n"
                    f"Hotel: "
                    f"{cancelled_booking.hotel_name}\n"
                    f"Provider: "
                    f"{cancelled_booking.provider}\n"
                    f"Destination: "
                    f"{cancelled_booking.destination}\n"
                    f"Check-in: "
                    f"{cancelled_booking.check_in_date}\n"
                    f"Check-out: "
                    f"{cancelled_booking.check_out_date}\n"
                    f"Travellers: "
                    f"{cancelled_booking.travellers}\n"
                    f"Nights: "
                    f"{cancelled_booking.nights}\n"
                    f"Total: "
                    f"{cancelled_booking.total_price} "
                    f"{cancelled_booking.currency}\n"
                    f"Status: "
                    f"{cancelled_booking.status}"
                )

            # ------------------------------------------------
            # Transport booking
            # ------------------------------------------------

            else:

                cancelled_booking = (
                    BookingService(runtime.context.db).cancel_booking(
                        booking_id=booking_id,
                        user_id=user_id,
                        tenant_id=state["tenant_id"],
                    )
                )

                message = (
                    "Your booking has been "
                    "cancelled successfully.\n\n"
                    f"Booking ID: "
                    f"{cancelled_booking.booking_id}\n"
                    f"Option: "
                    f"{cancelled_booking.option_id}\n"
                    f"Mode: "
                    f"{cancelled_booking.mode}\n"
                    f"From: "
                    f"{cancelled_booking.origin}\n"
                    f"To: "
                    f"{cancelled_booking.destination}\n"
                    f"Travellers: "
                    f"{cancelled_booking.travellers}\n"
                    f"Status: "
                    f"{cancelled_booking.status}"
                )

        except PermissionError:

            return {
                "messages": [
                    AIMessage(
                        content=(
                            "You are not allowed to cancel "
                            f"booking {booking_id}."
                        )
                    )
                ]
            }

        except ValueError as exc:

            return {
                "messages": [
                    AIMessage(
                        content=str(exc)
                    )
                ]
            }

        except Exception:

            return {
                "messages": [
                    AIMessage(
                        content=(
                            "I couldn't cancel the booking "
                            "right now. Please try again."
                        )
                    )
                ]
            }


        return {
            "messages": [
                AIMessage(
                    content=message
                )
            ],

            # No pending booking confirmation remains.
            "pending_booking_confirmation": False,

            # No booking domain remains pending.
            "pending_booking_domain": None,

            # Cancellation has been completed.
            # Clear the booking ID waiting for cancellation confirmation.
            "pending_cancellation_booking_id": None,

            # Clear selected option.
            "selected_option_id": None,
        }

    def cancel_booking_node(
        self,
        state: TravelState,
        runtime: Runtime[GraphContext],
    ) -> TravelState:
        """
        Start cancellation of an existing booking.

        This node:
            1. Reads the booking ID.
            2. Verifies that the booking exists and belongs
            to the current user.
            3. Checks whether it is already cancelled.
            4. Stores it as pending cancellation only when
            explicit confirmation is still required.
            5. Does NOT modify the database.

        Actual cancellation happens only after the user
        confirms with "Yes".
        """

        # ----------------------------------------------------
        # Get perception
        # ----------------------------------------------------

        perception = state.get("perception")

        if not perception:
            state["answer"] = (
                "I couldn't understand which booking "
                "you want to cancel."
            )
            return state

        # ----------------------------------------------------
        # Get booking ID
        # ----------------------------------------------------

        booking_id = getattr(
            perception,
            "booking_id",
            None,
        )

        if not booking_id:
            state["answer"] = (
                "Please provide the booking ID "
                "you want to cancel."
            )
            return state

        user_id = state["user_id"]

        # ====================================================
        # 1. Try HOTEL booking
        # ====================================================

        try:
            hotel_booking = (
                HotelBookingService(runtime.context.db).get_booking(
                    booking_id,
                    user_id,
                    state["tenant_id"],
                )
            )

            # Already cancelled
            if hotel_booking.status == "cancelled":
                state["answer"] = (
                    f"Hotel booking {booking_id} "
                    "is already cancelled."
                )

                state["pending_cancellation_booking_id"] = None

                return state

            # Only confirmed bookings should proceed
            # to cancellation confirmation.
            if hotel_booking.status != "confirmed":
                state["answer"] = (
                    f"Hotel booking {booking_id} cannot be "
                    f"cancelled because its current status is "
                    f"{hotel_booking.status}."
                )

                state["pending_cancellation_booking_id"] = None

                return state

            # Valid confirmed hotel booking.
            state["pending_cancellation_booking_id"] = (
                booking_id
            )

            state["answer"] = (
                f"Are you sure you want to cancel booking "
                f"{booking_id}?\n\n"
                "This action will change the booking status. "
                "Please reply Yes or No."
            )

            return state

        except ValueError:
            # Not a hotel booking.
            pass

        # ====================================================
        # 2. Try TRANSPORT booking
        # ====================================================

        try:
            booking = BookingService(runtime.context.db).get_booking(
                booking_id,
                user_id,
                state["tenant_id"],
            )

            # Already cancelled
            if booking.status == "cancelled":
                state["answer"] = (
                    f"Booking {booking_id} "
                    "is already cancelled."
                )

                state["pending_cancellation_booking_id"] = None

                return state

            # Only confirmed bookings should proceed
            # to cancellation confirmation.
            if booking.status != "confirmed":
                state["answer"] = (
                    f"Booking {booking_id} cannot be "
                    f"cancelled because its current status is "
                    f"{booking.status}."
                )

                state["pending_cancellation_booking_id"] = None

                return state

            # Valid confirmed transport booking.
            state["pending_cancellation_booking_id"] = (
                booking_id
            )

            state["answer"] = (
                f"Are you sure you want to cancel booking "
                f"{booking_id}?\n\n"
                "This action will change the booking status. "
                "Please reply Yes or No."
            )

            return state

        except ValueError:
            pass

        # ====================================================
        # 3. Booking not found
        # ====================================================

        state["answer"] = (
            f"I couldn't find any booking with ID "
            f"{booking_id}."
        )

        state["pending_cancellation_booking_id"] = None

        return state

