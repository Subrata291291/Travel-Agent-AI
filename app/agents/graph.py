        booking_id = state.get(
            "pending_cancellation_booking_id"
        )

        print(">>> CANCELLATION REQUEST REJECTED")

        return {
            "answer": (
                f"Okay. Booking {booking_id} was not cancelled."
                if booking_id
                else "Okay. The cancellation request was cancelled."
            ),
            "pending_cancellation_booking_id": None,
        }
    
